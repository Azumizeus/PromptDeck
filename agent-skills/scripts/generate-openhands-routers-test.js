#!/usr/bin/env node

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { afterEach, test } = require('node:test');

const {
  generateRouters,
  PHASE_ROUTERS,
  collidesAsSubstring,
  renderRouter,
} = require('./generate-openhands-routers.js');

const sandboxes = [];

function makeSandbox() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-skills-gen-routers-test-'));
  sandboxes.push(root);
  return root;
}

/**
 * Materialize a sandbox with the real skills/ corpus copied in (the generator
 * reads real descriptions via run-evals' loadSkills, which is repo-hardcoded,
 * so tests run the real generator through spawn with cwd pointing at the
 * sandbox and a copied scripts/ tree).
 */
function makeRepoSandbox() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-skills-gen-routers-repo-'));
  const repo = path.join(__dirname, '..');
  fs.mkdirSync(path.join(root, 'scripts'), { recursive: true });
  fs.cpSync(path.join(repo, 'skills'), path.join(root, 'skills'), { recursive: true });
  for (const f of ['generate-openhands-routers.js', 'run-evals.js', 'openhands-loader-sim.js', 'validate-openhands-microagent.js']) {
    fs.copyFileSync(path.join(repo, 'scripts', f), path.join(root, 'scripts', f));
  }
  sandboxes.push(root);
  return root;
}

function runGenerator(root, args = []) {
  return spawnSync(process.execPath, [path.join(root, 'scripts', 'generate-openhands-routers.js'), ...args], {
    cwd: root,
    encoding: 'utf8',
  });
}

afterEach(() => {
  for (const root of sandboxes.splice(0)) {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

// ─── Unit: collision semantics ───────────────────────────────────────────────

test('collidesAsSubstring flags embedding words but not identity', () => {
  const probes = new Set(['unspecified', 'reviewer', 'ship']);
  assert.equal(collidesAsSubstring('spec', probes), true);   // spec ⊂ unspecified
  assert.equal(collidesAsSubstring('view', probes), true);   // view ⊂ reviewer
  assert.equal(collidesAsSubstring('ship', probes), false);  // identity is fine
  assert.equal(collidesAsSubstring('plan', probes), false);
});

// ─── Unit: rendering is deterministic and frontmatter-complete ───────────────

test('renderRouter emits valid frontmatter, marker comment, and skill links', () => {
  const router = PHASE_ROUTERS.find(r => r.name === 'route-build');
  const content = renderRouter(router, ['build', 'code']);
  assert.match(content, /^---\nname: route-build\n/);
  assert.match(content, /phase: BUILD/);
  assert.match(content, /triggers:\n- build\n- code\n/);
  assert.match(content, /Generated by scripts\/generate-openhands-routers\.js/);
  assert.match(content, /skills\/incremental-implementation\/SKILL\.md/);
  assert.match(content, /skills\/test-driven-development\/SKILL\.md/);
  assert.equal(renderRouter(router, ['build', 'code']), content); // deterministic
});

// ─── Real-repo generation behavior ───────────────────────────────────────────

test('generation writes routers whose triggers pass the substring sanity bar', () => {
  const root = makeRepoSandbox();
  const result = runGenerator(root);
  assert.equal(result.status, 0, result.stdout + result.stderr);

  const { generateRouters: regen } = require(path.join(root, 'scripts', 'generate-openhands-routers.js'));
  const { summary } = regen({ check: true });
  for (const entry of summary) {
    assert.ok(entry.triggers.length > 0, `${entry.file} produced no triggers`);
    for (const t of entry.triggers) {
      assert.match(t, /^[a-z0-9 -]+$/, `${entry.file} trigger "${t}" is not plain`);
    }
  }
});

test('--check fails when a generated router drifts from disk', () => {
  const root = makeRepoSandbox();
  assert.equal(runGenerator(root).status, 0);
  // Hand-drift the file: a manual edit the generator did not produce.
  const file = path.join(root, '.openhands', 'microagents', 'route-bug.md');
  fs.writeFileSync(file, fs.readFileSync(file, 'utf8').replace('- bug\n', ''));

  const check = runGenerator(root, ['--check']);

  assert.equal(check.status, 1, check.stdout + check.stderr);
  assert.match(check.stdout + check.stderr, /Generated routers drifted from disk \(route-bug\.md\)/);
});

test('--check passes on a freshly generated, untouched tree', () => {
  const root = makeRepoSandbox();
  assert.equal(runGenerator(root).status, 0);

  const check = runGenerator(root, ['--check']);

  assert.equal(check.status, 0, check.stdout + check.stderr);
  assert.match(check.stdout, /All generated routers match disk — PASSED/);
});

test('generated routers satisfy the repo validator and simulator', () => {
  const root = makeRepoSandbox();
  assert.equal(runGenerator(root).status, 0);
  // The validator and simulator are needed in-sandbox for the cross-check.
  const repo = path.join(__dirname, '..');
  for (const f of ['validate-openhands-microagent.js', 'openhands-loader-sim.js']) {
    fs.copyFileSync(path.join(repo, 'scripts', f), path.join(root, 'scripts', f));
  }
  fs.writeFileSync(path.join(root, 'AGENTS.md'), fs.readFileSync(path.join(repo, 'AGENTS.md'), 'utf8'));
  // The validator and simulator both require the always-loaded startup
  // microagent; the generator only produces route-*.md, so seed it here.
  fs.mkdirSync(path.join(root, '.openhands', 'microagents'), { recursive: true });
  fs.copyFileSync(
    path.join(repo, '.openhands', 'microagents', 'list-loaded-skills.md'),
    path.join(root, '.openhands', 'microagents', 'list-loaded-skills.md'),
  );

  const validator = spawnSync(process.execPath, [path.join(root, 'scripts', 'validate-openhands-microagent.js')], { cwd: root, encoding: 'utf8' });
  assert.equal(validator.status, 0, validator.stdout + validator.stderr);

  const sim = spawnSync(process.execPath, [path.join(root, 'scripts', 'openhands-loader-sim.js')], { cwd: root, encoding: 'utf8' });
  assert.equal(sim.status, 0, sim.stdout + sim.stderr);
});

test('the real repository is in sync with its generated routers', () => {
  // Guards the checked-in .openhands/microagents/route-*.md files: if someone
  // edits a router (or a skill description shifts vocabulary) without
  // regenerating, this catches it.
  const result = spawnSync(process.execPath, [path.join(__dirname, 'generate-openhands-routers.js'), '--check'], {
    cwd: path.join(__dirname, '..'),
    encoding: 'utf8',
  });

  assert.equal(result.status, 0, result.stdout + result.stderr);
});
